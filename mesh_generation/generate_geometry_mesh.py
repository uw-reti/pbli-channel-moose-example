"""Write a Cardinal/MOOSE mesh input matching hardcoded_pipe_structure_mesh.i.

Read pipe and channel bounds from the geometry JSON in centimeters and
write a Cardinal input in meters.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# The geometry module lives one directory above this script.
EXAMPLE_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(EXAMPLE_DIR))

from model_geometry_object import Box, ModelGeometryObject

# Grid counts in (nx, ny, nz) order.
STRUCTURE_COUNTS = (28, 25, 20)  # steel envelope before channel cutouts
LEFT_COARSE_COUNTS = (1, 25, 1)  # heating
RIGHT_COARSE_COUNTS = (1, 25, 1)
LEFT_FINE_COUNTS = (5, 25, 6)  # tritium
RIGHT_FINE_COUNTS = (4, 25, 6)


def format_meters(cm: float) -> str:
    """Convert centimeters to the meter format used by the mesh input."""
    text = f"{cm / 100.0:.2f}"
    return "0.0" if text == "0.00" else text


def generated_box(name: str, box: Box, counts: tuple[int, int, int], block_id: int) -> str:
    """Write a uniform grid covering the given box."""
    nx, ny, nz = counts
    xmin, ymin, zmin = (format_meters(v) for v in box.lower)
    xmax, ymax, zmax = (format_meters(v) for v in box.upper)
    return f"""  [{name}]
    type = GeneratedMeshGenerator
    dim = 3
    xmin = {xmin}
    xmax = {xmax}
    ymin = {ymin}
    ymax = {ymax}
    zmin = {zmin}
    zmax = {zmax}
    nx = {nx}
    ny = {ny}
    nz = {nz}
    subdomain_ids = {block_id}
  []"""


def channel_cutout(name: str, parent: str, box: Box, block_id: int) -> str:
    """Tag channel cells in an existing grid for later deletion."""
    lower = " ".join(format_meters(v) for v in box.lower)
    upper = " ".join(format_meters(v) for v in box.upper)
    return f"""  [{name}]
    type = SubdomainBoundingBoxGenerator
    input = {parent}
    block_id = {block_id}
    bottom_left = '{lower}'
    top_right = '{upper}'
  []"""


def validate_channel_alignment(geometry: ModelGeometryObject) -> None:
    """Require channel corners to lie on structure element faces."""
    pipe = geometry.pipe
    for name, channel in (
        ("left", geometry.left_channel),
        ("right", geometry.right_channel),
    ):
        for corner in (channel.lower, channel.upper):
            for axis, value, origin, length, count in zip(
                "xyz", corner, pipe.lower, pipe.dimensions, STRUCTURE_COUNTS
            ):
                # Structure element faces land at integer grid coordinates.
                grid_coordinate = (value - origin) * count / length
                if abs(grid_coordinate - round(grid_coordinate)) > 1e-8:
                    raise ValueError(
                        f"The {name} channel face at {axis} = {value:g} cm "
                        f"does not align with the structure grid {STRUCTURE_COUNTS}."
                    )


def build_mesh_input(geometry: ModelGeometryObject) -> str:
    """Build the structure, coolant, and combined tally mesh blocks."""
    left = geometry.left_channel
    right = geometry.right_channel

    return f"""# Generated by generate_geometry_mesh.py (same layout as hardcoded_pipe_structure_mesh.i).
# Mesh outputs:
#   tally_domain_in.e      — structure + coarse + fine coolant (openmc.i)
#   pipe_structure_mesh.e  — structure + coarse coolant only (--mesh-only)
# Coarse/fine coolant blocks overlap; restrict every tally by block.
# Coolant and structure do not share interface nodes.

[Mesh]
  allow_renumbering = false

  # Full outer pipe box (1 cm x 2 cm x 1 cm structure cells).
{generated_box("pipe", geometry.pipe, STRUCTURE_COUNTS, 2)}

  # Tag left-channel cells in the pipe mesh.
{channel_cutout("left_channel", "pipe", left, 3)}

  # Tag right-channel cells (input is the mesh after left tagging).
{channel_cutout("right_channel", "left_channel", right, 4)}

  # Delete tagged channel cells so structure has voids for coolant meshes.
  [structure]
    type = BlockDeletionGenerator
    input = right_channel
    block = '3 4'
  []

  # Coarse left channel for heating ({LEFT_COARSE_COUNTS[0]} x {LEFT_COARSE_COUNTS[1]} x {LEFT_COARSE_COUNTS[2]}).
{generated_box("left_coarse", left, LEFT_COARSE_COUNTS, 3)}

  # Coarse right channel for heating ({RIGHT_COARSE_COUNTS[0]} x {RIGHT_COARSE_COUNTS[1]} x {RIGHT_COARSE_COUNTS[2]}).
{generated_box("right_coarse", right, RIGHT_COARSE_COUNTS, 4)}

  # Fine left channel for tritium ({LEFT_FINE_COUNTS[0]} x {LEFT_FINE_COUNTS[1]} x {LEFT_FINE_COUNTS[2]}).
{generated_box("left_fine", left, LEFT_FINE_COUNTS, 5)}

  # Fine right channel for tritium ({RIGHT_FINE_COUNTS[0]} x {RIGHT_FINE_COUNTS[1]} x {RIGHT_FINE_COUNTS[2]}).
{generated_box("right_fine", right, RIGHT_FINE_COUNTS, 6)}

  # Join structure + coarse + fine (still numeric block IDs).
  [assemble]
    type = MeshCollectionGenerator
    inputs = 'structure left_coarse right_coarse left_fine right_fine'
  []

  # Name blocks for openmc.i and write tally_domain_in.e.
  # Coarse → left_channel/right_channel; fine → left_tritium/right_tritium.
  [tally_domain]
    type = RenameBlockGenerator
    input = assemble
    old_block = '2 3 4 5 6'
    new_block = 'pipe_structure left_channel right_channel left_tritium right_tritium'
    output = true
  []

  # Drop fine coolant from the final mesh; names on the rest are kept.
  [heating_domain]
    type = BlockDeletionGenerator
    input = tally_domain
    block = 'left_tritium right_tritium'
  []
[]
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--geometry",
        type=Path,
        default=EXAMPLE_DIR / "pipe_geometry_info.json",
        help="JSON geometry file (cm)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("generated_pipe_structure_mesh.i"),
        help="Path for the generated HIT mesh input",
    )
    args = parser.parse_args()

    geometry = ModelGeometryObject(geometry_file=args.geometry)
    try:
        validate_channel_alignment(geometry)
    except ValueError as exc:
        parser.error(str(exc))

    args.output.write_text(build_mesh_input(geometry), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
